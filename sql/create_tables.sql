-- ============================================================================
-- Classroom Booking and Timetable Management System
-- File: create_tables.sql
-- Description: DDL table definitions (3NF normalized) with primary keys,
--              foreign keys, NOT NULL constraints, and CHECK constraints.
-- ============================================================================

-- 1. DEPARTMENT Table
CREATE TABLE DEPARTMENT (
    dept_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_code        VARCHAR2(10)  NOT NULL UNIQUE,
    dept_name        VARCHAR2(100) NOT NULL,
    office_location  VARCHAR2(100)
);

-- 2. FACULTY Table
CREATE TABLE FACULTY (
    faculty_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_code     VARCHAR2(20)  NOT NULL UNIQUE,
    first_name       VARCHAR2(50)  NOT NULL,
    last_name        VARCHAR2(50)  NOT NULL,
    email            VARCHAR2(100) NOT NULL UNIQUE,
    dept_id          NUMBER        NOT NULL REFERENCES DEPARTMENT(dept_id),
    designation      VARCHAR2(50)  DEFAULT 'Assistant Professor'
);

-- 3. COURSE Table
CREATE TABLE COURSE (
    course_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code      VARCHAR2(20)  NOT NULL UNIQUE,
    course_title     VARCHAR2(150) NOT NULL,
    credits          NUMBER(2)     DEFAULT 3 NOT NULL CHECK (credits > 0),
    dept_id          NUMBER        NOT NULL REFERENCES DEPARTMENT(dept_id)
);

-- 4. ROOM Table
CREATE TABLE ROOM (
    room_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number      VARCHAR2(20)  NOT NULL UNIQUE,
    building         VARCHAR2(50)  NOT NULL,
    floor            NUMBER(2)     NOT NULL,
    room_type        VARCHAR2(20)  NOT NULL CHECK (room_type IN ('CLASSROOM', 'LAB', 'SEMINAR_HALL')),
    capacity         NUMBER(4)     NOT NULL CHECK (capacity > 0)
);

-- 5. FACILITY Table
CREATE TABLE FACILITY (
    facility_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_name    VARCHAR2(50)  NOT NULL UNIQUE,
    description      VARCHAR2(200)
);

-- 6. ROOM_FACILITY (Associative table for M:N relationship between ROOM and FACILITY)
CREATE TABLE ROOM_FACILITY (
    room_id          NUMBER        NOT NULL REFERENCES ROOM(room_id) ON DELETE CASCADE,
    facility_id      NUMBER        NOT NULL REFERENCES FACILITY(facility_id) ON DELETE CASCADE,
    quantity         NUMBER(3)     DEFAULT 1 NOT NULL CHECK (quantity > 0),
    CONSTRAINT pk_room_facility PRIMARY KEY (room_id, facility_id)
);

-- 7. SEMESTER Table
CREATE TABLE SEMESTER (
    semester_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_name    VARCHAR2(50)  NOT NULL UNIQUE,
    start_date       DATE          NOT NULL,
    end_date         DATE          NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL CHECK (is_active IN (0, 1)),
    CONSTRAINT chk_semester_dates CHECK (end_date > start_date)
);

-- 8. TIME_SLOT Table
CREATE TABLE TIME_SLOT (
    slot_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_name        VARCHAR2(50)  NOT NULL,
    start_time       VARCHAR2(5)   NOT NULL, -- HH24:MI e.g. '08:30'
    end_time         VARCHAR2(5)   NOT NULL, -- HH24:MI e.g. '09:30'
    slot_order       NUMBER(2)     NOT NULL UNIQUE,
    CONSTRAINT chk_slot_time CHECK (end_time > start_time)
);

-- 9. BOOKING Table (Parent Booking Record)
CREATE TABLE BOOKING (
    booking_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_type     VARCHAR2(20)  NOT NULL CHECK (booking_type IN ('PERIODIC', 'ONEOFF')),
    room_id          NUMBER        NOT NULL REFERENCES ROOM(room_id),
    faculty_id       NUMBER        NOT NULL REFERENCES FACULTY(faculty_id),
    course_id        NUMBER        REFERENCES COURSE(course_id),
    title_purpose    VARCHAR2(200) NOT NULL,
    day_of_week      VARCHAR2(10)  CHECK (day_of_week IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday')),
    slot_id          NUMBER        NOT NULL REFERENCES TIME_SLOT(slot_id),
    semester_id      NUMBER        REFERENCES SEMESTER(semester_id),
    created_at       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 10. BOOKING_OCCURRENCE Table (Concrete Date Occurrence)
CREATE TABLE BOOKING_OCCURRENCE (
    occurrence_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           NUMBER        NOT NULL REFERENCES BOOKING(booking_id) ON DELETE CASCADE,
    occurrence_date      DATE          NOT NULL,
    slot_id              NUMBER        NOT NULL REFERENCES TIME_SLOT(slot_id),
    room_id              NUMBER        NOT NULL REFERENCES ROOM(room_id),
    faculty_id           NUMBER        NOT NULL REFERENCES FACULTY(faculty_id),
    status               VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'CANCELLED')),
    cancellation_reason  VARCHAR2(255),
    updated_at           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);
